#include <iostream>
using namespace std;
int main()
{
    int a = 2;          // integer datatype
    double const b = 4;   //constant and also not changable don't use another variable to change the value of b
    float c = 1.4;       // float datatypr for declaring decimals
    char d = 'A';        // character datatype
    cout << a << "\n" << b << "\n" << c << "\n" << d << "\n";
    return 0;
}